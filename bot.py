STOP_STEMS = {"есть", "дома", "хочу", "приго", "блюдо", "блюда", "надо", "нужн", "можно", "рецеп", "что-н", "чтоб"}


def mode_cats(mode: str) -> list:
    if mode == "healthy":
        return [c for c in HEALTHY_CATS if c in CATALOG]
    return [c for c in CATALOG if c not in HEALTHY_CATS]  # «Обычное»: всё, кроме диетических разделов


def stem_matches(text: str, pool) -> list:
    stems = {w[:5] for w in re.findall(r"[а-яёa-z]{4,}", text)} - STOP_STEMS
    found = [d for d in pool if any(st in d.lower() for st in stems)]
    random.shuffle(found)
    return found


def pick_candidates(text: str, mode: str = "regular"):
    """Возвращает (разделы с блюдами для нейросети, блюда, прямо совпавшие с запросом)."""
    t = text.lower()
    allowed = mode_cats(mode)
    out: dict = {}
    if mode == "healthy":
        out = {c: list(CATALOG[c]) for c in allowed}  # здоровый каталог небольшой, показываем целиком
    else:
        cats = []
        for key, cs in INTENTS.items():
            if key in t:
                cats += [c for c in cs if c in allowed and c not in cats]
        if cats:
            per = max(14, min(30, 70 // len(cats)))
            for c in cats:
                out[c] = random.sample(CATALOG[c], min(per, len(CATALOG[c])))
        else:
            for c in allowed:
                out[c] = random.sample(CATALOG[c], min(8, len(CATALOG[c])))
    pool = {d for c in allowed for d in CATALOG[c]}
    matched = stem_matches(t, pool)
    for d in matched[:40]:
        lst = out.setdefault(DISH_CAT[d], [])
        if d not in lst:
            lst.append(d)
    return out, matched[:12]


def plural(n: int, a: str, b: str, c: str) -> str:
    n = abs(n)
    if n % 10 == 1 and n % 100 != 11:
        return a
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return b
    return c


