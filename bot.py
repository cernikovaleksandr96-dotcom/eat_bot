async def api_data(request: web.Request) -> web.Response:
    """Любимые блюда и свои рецепты хранятся на сервере, чтобы не пропадали при очистке данных Telegram."""
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"error": "Некорректный запрос."}, status=400)
    uid = user_id_from_init_data(str(body.get("initData", "")))
    if uid is None:
        return web.json_response({"error": "Открой приложение кнопкой из Telegram."}, status=403)
    path = DATA_DIR / f"{int(uid)}.json"
    if "data" in body:
        data = body["data"]
        if not isinstance(data, dict):
            return web.json_response({"error": "Нет данных."}, status=400)
        data = {k: data[k] for k in ("my", "fav", "nid", "ts") if k in data}
        raw = json.dumps(data, ensure_ascii=False)
        if len(raw.encode("utf-8")) > MAX_USER_DATA:
            return web.json_response({"error": "Слишком много данных."}, status=413)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(raw, encoding="utf-8")
        tmp.replace(path)
        return web.json_response({"ok": True})
    try:
        return web.json_response({"data": json.loads(path.read_text(encoding="utf-8"))})
    except FileNotFoundError:
        return web.json_response({"data": None})
    except Exception:
        logging.exception("data read error")
        return web.json_response({"data": None})


