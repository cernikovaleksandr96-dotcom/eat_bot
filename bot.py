def _build_models() -> list:
    """Цепочка нейросетей: если у одной кончились лимиты или она упала, берём следующую."""
    ms = []

    def add(provider, url, key, names, json_mode):
        for name in names.split(","):
            name = name.strip()
            if name:
                ms.append({
                    "id": f"{provider}:{name}", "label": name, "url": url, "key": key, "model": name,
                    "gpt_oss": name.startswith("openai/gpt-oss"), "json_mode": json_mode,
                })

    if opt("GROQ_API_KEY"):
        add("groq", "https://api.groq.com/openai/v1/chat/completions", opt("GROQ_API_KEY"),
            os.getenv("GROQ_MODELS", "openai/gpt-oss-120b,openai/gpt-oss-20b,llama-3.3-70b-versatile,llama-3.1-8b-instant"), True)
    if opt("OPENROUTER_API_KEY"):
        add("openrouter", "https://openrouter.ai/api/v1/chat/completions", opt("OPENROUTER_API_KEY"),
            os.getenv("OPENROUTER_MODELS", "meta-llama/llama-3.3-70b-instruct:free"), False)
    if opt("GEMINI_API_KEY"):
        add("gemini", "https://generativelanguage.googleapis.com/v1beta/openai/chat/completions", opt("GEMINI_API_KEY"),
            os.getenv("GEMINI_MODELS", "gemini-2.5-flash"), False)
    return ms


