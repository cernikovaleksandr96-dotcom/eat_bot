def format_summary(data: dict) -> str:
    parts = []
    if data.get("menu"):
        days = {}
        for day, meal, name in data["menu"]:
            days.setdefault(day, []).append(f"{meal.lower()}: {name}")
        parts.append(
            "📅 Меню на неделю:\n"
            + "\n\n".join(f"{day}\n" + "\n".join(f"  • {x}" for x in items) for day, items in days.items())
        )
    if data.get("shopping"):
        parts.append("🛒 Купить:\n" + "\n".join(f"• {x}" for x in data["shopping"]))
    return "\n\n".join(parts) or "Список пуст — всё нужное уже есть дома."


