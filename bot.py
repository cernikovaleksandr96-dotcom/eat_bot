def user_id_from_init_data(init_data: str):
    """Проверяем подпись Telegram: запрос действительно пришёл из мини-приложения."""
    try:
        d = dict(urllib.parse.parse_qsl(init_data, keep_blank_values=True))
        got = d.pop("hash")
        check = "\n".join(f"{k}={v}" for k, v in sorted(d.items()))
        key = hmac.new(b"WebAppData", BOT_TOKEN.encode(), hashlib.sha256).digest()
        if not hmac.compare_digest(hmac.new(key, check.encode(), hashlib.sha256).hexdigest(), got):
            return None
        if time.time() - int(d.get("auth_date", 0)) > 86400:
            return None
        return json.loads(d["user"])["id"]
    except Exception:
        return None


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s-]", "", str(s).lower().replace("ё", "е"))).strip()


NORM_DISHES = {norm(d): d for d in ALL_DISHES}


def match_dish(name: str):
    """Название от нейросети -> точное название из каталога (допускаем мелкие расхождения: регистр, ё, пробелы, опечатка)."""
    key = norm(name)
    if key in NORM_DISHES:
        return NORM_DISHES[key]
    close = difflib.get_close_matches(key, NORM_DISHES.keys(), n=1, cutoff=0.88)
    return NORM_DISHES[close[0]] if close else None


def to_int(v, default=0) -> int:
    m = re.search(r"\d+", str(v))
    return int(m.group()) if m else default


def as_list(v) -> list:
    if isinstance(v, str):
        v = re.split(r"[,;]", v)
    return [str(x).strip().lower()[:30] for x in (v or []) if str(x).strip()][:10]


def clean(data: dict, n: int = 6) -> list:
    out, seen = [], set()
    for r in (data.get("recipes") or []):
        if len(out) >= n:
            break
        try:
            name = match_dish(r["name"])
            if not name or name in seen:
                continue
            seen.add(name)
            have, miss = as_list(r.get("have")), as_list(r.get("missing"))
            steps_raw = r.get("steps") or []
            if isinstance(steps_raw, str):
                steps_raw = [steps_raw]
            steps = "\n".join(
                "{}. {}".format(i, re.sub(r"^\d+[.)]\s*", "", str(t).strip())) for i, t in enumerate(steps_raw, 1)
            )
            out.append({
                "n": name,
                "c": DISH_CAT[name],
                "e": (str(r.get("emoji") or "🍽").strip() or "🍽")[:4],
                "t": to_int(r.get("time"), 20) or 20,
                "k": to_int(r.get("kcal"), 0),
                "h": have,
                "i": have + miss,
                "s": steps[:900],
                "q": str(r.get("q") or "").strip()[:200],
            })
        except Exception:
            continue
    return out


class Skip(Exception):
    """Эту модель сейчас нельзя использовать, переходим к следующей."""

    def __init__(self, why: str, cool: float = 0, gone: bool = False):
        super().__init__(why)
        self.why, self.cool, self.gone = why, cool, gone


class AllBusy(Exception):
    def __init__(self, wait: float):
        super().__init__("all models busy")
        self.wait = wait


def extract_json(content: str) -> dict:
    content = content.strip()
    content = re.sub(r"^```(?:json)?|```$", "", content, flags=re.M).strip()
    try:
        return json.loads(content)
    except Exception:
        a, b = content.find("{"), content.rfind("}")
        if a >= 0 < b:
            return json.loads(content[a:b + 1])
        raise


async def call_model(session: aiohttp.ClientSession, m: dict, system: str, user: str) -> dict:
    payload = {
        "model": m["model"],
        "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        "temperature": 0.6,
        "max_tokens": 4500,  # запас, чтобы модель с рассуждением не вернула пустой ответ
    }
    if m["gpt_oss"]:
        payload["reasoning_effort"] = "low"
    if m["json_mode"]:
        payload["response_format"] = {"type": "json_object"}
    try:
        async with session.post(
            m["url"], json=payload, headers={"Authorization": f"Bearer {m['key']}"},
            timeout=aiohttp.ClientTimeout(total=45),
        ) as r:
            if r.status != 200:
                body = (await r.text())[:300]
                logging.warning("%s -> HTTP %s: %s", m["id"], r.status, body)
                if r.status == 429:
                    try:
                        ra = float(r.headers.get("retry-after", 60))
                    except ValueError:
                        ra = 60
                    raise Skip("лимит", cool=min(max(ra, 5), 6 * 3600))
                if r.status in (401, 403):
                    raise Skip("ключ не принят", cool=3600)
                if r.status == 404 or (r.status == 400 and re.search(r"decommission|not found|does not exist|no longer", body, re.I)):
                    raise Skip("модели нет", gone=True)
                if r.status >= 500 or r.status == 413:
                    raise Skip("сбой сервиса", cool=30)
                raise Skip(f"ошибка {r.status}")
            j = await r.json()
    except (aiohttp.ClientError, asyncio.TimeoutError) as e:
        raise Skip(f"сеть: {e}", cool=20)
    content = ((j.get("choices") or [{}])[0].get("message") or {}).get("content") or ""
    if not content.strip():
        raise Skip("пустой ответ")
    try:
        return extract_json(content)
    except Exception:
        raise Skip("ответ не JSON")


async def ask_ai(text: str, mode: str, n: int, servings: int, avoid: str) -> dict:
    system = build_system(text, mode, n, servings, avoid)
    answered_empty, note, tried = False, "", 0
    async with aiohttp.ClientSession() as s:
        for m in MODELS:
            if m["id"] in dead or cooldown.get(m["id"], 0) > time.time():
                continue
            tried += 1
            try:
                data = await call_model(s, m, system, text)
            except Skip as e:
                logging.warning("Модель %s пропущена: %s", m["id"], e.why)
                if e.gone:
                    dead.add(m["id"])
                elif e.cool:
                    cooldown[m["id"]] = time.time() + e.cool
                continue
            recipes = clean(data, n)
            if recipes:
                logging.info("Ответила модель %s", m["id"])
                return {"recipes": recipes, "note": "", "model": m["label"]}
            # пустой ответ: пробуем следующую модель, но запоминаем пояснение первой
            answered_empty = True
            note = note or str(data.get("note") or "")[:200]
            logging.info("Модель %s не вернула рецептов, пробую следующую", m["id"])
            if tried >= 3:
                break
    if answered_empty:
        return {
            "recipes": [],
            "note": note or "Не нашлось подходящих блюд. Напиши продукты через запятую, например: яйца, молоко, мука.",
            "model": "",
        }
    waits = [cooldown[m["id"]] - time.time() for m in MODELS if m["id"] not in dead and cooldown.get(m["id"], 0) > time.time()]
    raise AllBusy(min(waits) if waits else 0)


async def api_recipes(request: web.Request) -> web.Response:
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"error": "Некорректный запрос."}, status=400)
    uid = user_id_from_init_data(str(body.get("initData", "")))
    if uid is None:
        return web.json_response({"error": "Открой приложение кнопкой из Telegram."}, status=403)
    text = str(body.get("q", "")).strip()[:500]
    if not text:
        return web.json_response({"error": "Напиши, какие продукты есть."}, status=400)
    mode = "healthy" if body.get("mode") == "healthy" else "regular"
    n = min(8, max(3, to_int(body.get("n"), 6)))
    servings = min(8, max(1, to_int(body.get("servings"), 2)))
    avoid = re.sub(r"[^\w\s,.-]", "", str(body.get("avoid", "")))[:150].strip()
    now = time.time()
    hits[uid] = [t for t in hits[uid] if now - t < WINDOW]
    if len(hits[uid]) >= LIMIT:
        return web.json_response({"error": "Лимит запросов, попробуй через час."}, status=429)
    hits[uid].append(now)
    try:
        return web.json_response(await ask_ai(text, mode, n, servings, avoid))
    except AllBusy as e:
        hits[uid].pop()  # неудачный запрос не считаем
        wait = f" Попробуй через {max(1, int(e.wait // 60) + 1)} мин." if e.wait else ""
        return web.json_response({"error": "Лимиты всех нейросетей сейчас исчерпаны." + wait}, status=503)
    except Exception:
        hits[uid].pop()
        logging.exception("AI error")
        return web.json_response({"error": "Нейросеть сейчас недоступна, попробуй чуть позже."}, status=502)


